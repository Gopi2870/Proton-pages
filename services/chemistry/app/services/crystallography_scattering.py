def calculate_atomic_form_factor(
    element: str,
    sin_theta_over_lambda: float,
    thermal_b: float = 0.5
) -> float:
    """
    Computes temperature-corrected atomic scattering factor:
        f(s) = f_0(s) * exp(-thermal_b * s^2)
    where s = sin(theta) / lambda.
    """
    s = max(0.0, float(sin_theta_over_lambda))
    s2 = s * s
    sym = element.strip().capitalize()

    if sym in CROMER_MANN_COEFFICIENTS:
        a1, b1, a2, b2, a3, b3, a4, b4, c = CROMER_MANN_COEFFICIENTS[sym]
        f0 = (
            a1 * math.exp(-b1 * s2) +
            a2 * math.exp(-b2 * s2) +
            a3 * math.exp(-b3 * s2) +
            a4 * math.exp(-b4 * s2) +
            c
        )
    else:
        # Classical Thomas-Fermi approximation fallback
        z = float(ELEMENT_ATOMIC_NUMBERS.get(sym, 6))
        # Standard analytical approximation for general atoms
        f0 = z / (1.0 + 3.0 * s2)

    # Prevent negative form factors at high angles
    f0 = max(0.0, f0)

    # Debye-Waller temperature factor
    temperature_factor = math.exp(-thermal_b * s2)
    return f0 * temperature_factor
